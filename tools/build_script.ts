/*
 * Regenerates src/story/script.ts from docs/STORY_BIBLE.md, so the bible stays
 * the single source of every line in the game.
 *
 *   node tools/build_script.ts          write src/story/script.ts
 *   node tools/build_script.ts --check  fail if script.ts is out of date
 *
 * Runs on Node 22.18+ (TypeScript type stripping, no build step). The parser
 * is src/story/bible.ts; tests/story.test.ts parses the bible the same way and
 * checks it against script.ts line by line.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGameBible as parseBible } from '../src/story/bible.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const biblePath = resolve(root, 'docs/STORY_BIBLE.md');
const outPath = resolve(root, 'src/story/script.ts');

/** Small leaf objects on one line each, everything else indented: readable diffs when the bible changes. */
function serialise(value: unknown, indent: string): string {
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    if (value.every((item) => typeof item !== 'object' || item === null)) return JSON.stringify(value);
    return `[\n${value.map((item) => `${indent}  ${serialise(item, `${indent}  `)}`).join(',\n')},\n${indent}]`;
  }
  if (value && typeof value === 'object') {
    const record = value as Record<string, unknown>;
    const leaf = ['line', 'dir', 'move'].includes(String(record.kind)) || (!('kind' in record) && Object.values(record).every((v) => typeof v !== 'object' || v === null || (Array.isArray(v) && v.every((x) => typeof x !== 'object'))));
    if (leaf) return JSON.stringify(value);
    const entries = Object.entries(record).filter(([, v]) => v !== undefined);
    return `{\n${entries.map(([k, v]) => `${indent}  ${JSON.stringify(k)}: ${serialise(v, `${indent}  `)}`).join(',\n')},\n${indent}}`;
  }
  return JSON.stringify(value);
}

const parts = parseBible(readFileSync(biblePath, 'utf8'));
const source = `/*
 * GENERATED by tools/build_script.ts from docs/STORY_BIBLE.md. Do not edit by hand:
 * change the bible and run \`node tools/build_script.ts\`. tests/story.test.ts
 * checks this file against the bible line by line.
 */
import type { BPart } from './bible';

export const BIBLE: readonly BPart[] = ${serialise(parts, '')};
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(outPath, 'utf8');
  if (current !== source) {
    console.error('src/story/script.ts is out of date: run node tools/build_script.ts');
    process.exit(1);
  }
  console.log('src/story/script.ts is up to date');
} else {
  writeFileSync(outPath, source);
  const lines = source.split('\n').length;
  console.log(`Wrote src/story/script.ts: ${parts.length} parts, ${lines} lines`);
}
